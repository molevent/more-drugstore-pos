## การคำนวณ VAT

ระบบคำนวณ VAT 7% จากยอดรวม:
- สูตร: `VAT = ยอดรวม × 7 ÷ 107`
- ฐานภาษี: `ยอดรวม - VAT`

**ตัวอย่าง**:
- ยอดรวม: 107 บาท
- VAT 7%: 7 บาท
- ฐานภาษี: 100 บาท

